"""Прогноз температуры на 8 дней для тренера Дениса.

Пробежка возможна, если температура одновременно не ниже 10
и не выше 20 градусов. Два условия соединяем оператором and.
"""

forecast = [5, 12, 22, 15, 10, 8, 20, 18]

good_days = []

for temp in forecast:
    if temp >= 10 and temp <= 20:
        good_days.append(temp)

print(good_days)
