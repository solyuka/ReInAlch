"""Агрегатор отзывов: рейтинг кофеен района.

В системе была одна оценка — 4.2, затем по очереди поступили 3.8, 4.9, 4.5, 3.5.
Программа добавляет их к списку, сортирует все оценки по возрастанию
функцией sorted() и выводит две первые (самые низкие) оценки,
чтобы аналитик занялся проблемными заведениями.
"""

ratings = [4.2]
ratings.append(3.8)
ratings.append(4.9)
ratings.append(4.5)
ratings.append(3.5)

sorted_ratings = sorted(ratings)

print(sorted_ratings[:2])
