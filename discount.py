"""Магазин одежды: скидка 20% на каждую покупку.

Программа считывает начальную цену товара (целое число рублей)
и выводит итоговую цену после скидки 20 процентов,
то есть 80 процентов от начальной цены.

Вывод — только итоговое число, без приглашений и пояснений:
этого требуют автоматические тесты.
"""

price = int(input())
final_price = price * 80 / 100

# Целое значение печатаем без «.0» (2500 -> 2000),
# дробное — как есть (2501 -> 2000.8).
if final_price == int(final_price):
    print(int(final_price))
else:
    print(final_price)
