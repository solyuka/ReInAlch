"""Чеки бариста Олега за смену.

Заказы: 180, 220, 150, 300, 180, 250, 200 (стоимость каждого в рублях).
Программа за один проход по списку накапливает общую выручку
и одновременно считает число заказов, затем выводит выручку,
а на следующей строке — количество заказов.
"""

orders = [180, 220, 150, 300, 180, 250, 200]

revenue = 0
orders_count = 0

for order in orders:
    revenue += order
    orders_count += 1

print(revenue)
print(orders_count)
